function darkMode() {
        var element = document.body;
        var element = document.address;
        var content = document.getElementById("DarkModetext");
        element.className = "dark-mode"; // applies CSS class "dark-mode" to body
}

function lightMode() {
        var element = document.body;
        var element = document.address;
        var content = document.getElementById("LightModetext");
        element.className = "light-mode"; // applies CSS class "light-mode" to body
}
